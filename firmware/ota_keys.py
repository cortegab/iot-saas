# PlatformIO pre-build script (extra_scripts in platformio.ini): turns the
# public update keys in ota_keys/*.pem into ota_keys.h for src/ota.cpp.
#
# These are PUBLIC keys (ECDSA P-256, "-----BEGIN PUBLIC KEY-----"): safe to
# commit. The private key that signs releases never enters the repo; it lives
# in the GitHub Actions secret OTA_SIGNING_KEY and an offline backup
# (docs/firmware/ota.md). Two slots at most: the current key and the next one,
# so the key can change with one ordinary update.
#
# No key file: the header has no keys, and the firmware refuses every update.
from pathlib import Path

Import("env")  # type: ignore[name-defined]  # noqa: F821

MAX_KEYS = 2
project = Path(env["PROJECT_DIR"])  # type: ignore[name-defined]  # noqa: F821
if env["PIOENV"] != "native":  # type: ignore[name-defined]  # noqa: F821
    keys = sorted((project / "ota_keys").glob("*.pem"))
    if len(keys) > MAX_KEYS:
        raise SystemExit(f"ota_keys.py: at most {MAX_KEYS} public keys in ota_keys/, found {len(keys)}")
    pems = []
    for path in keys:
        text = path.read_text().strip()
        if "PRIVATE KEY" in text:
            raise SystemExit(f"ota_keys.py: {path.name} is a PRIVATE key. Only public keys belong in ota_keys/.")
        if not text.startswith("-----BEGIN PUBLIC KEY-----"):
            raise SystemExit(f"ota_keys.py: {path.name} isn't a PEM public key")
        pems.append(text + "\n")
    out_dir = Path(env.subst("$BUILD_DIR")) / "generated"  # type: ignore[name-defined]  # noqa: F821
    out_dir.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(f'    R"PEM({pem})PEM"' for pem in pems)
    names = ", ".join(path.name for path in keys) or "none"
    header = (
        "#pragma once\n"
        "// Generated by ota_keys.py from ota_keys/*.pem: don't edit.\n"
        f"// Keys: {names}\n"
        "#include <stddef.h>\n"
        f"static constexpr size_t OTA_KEY_COUNT = {len(pems)};\n"
        + (f"static const char* const OTA_KEYS[] = {{\n{body}\n}};\n" if pems else "static const char* const* OTA_KEYS = nullptr;\n")
    )
    target = out_dir / "ota_keys.h"
    if not target.exists() or target.read_text() != header:
        target.write_text(header)
    env.Append(CPPPATH=[str(out_dir)])  # type: ignore[name-defined]  # noqa: F821
